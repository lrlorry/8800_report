#!/usr/bin/env python3
"""Audit Chapter 7's second review from archived records; never runs CUDA."""
import collections
import csv
import hashlib
import importlib.util
import json
import math
import re
import statistics as st
import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT.parent / 'JHQ_GPU'
DATASETS = ['vogue-768', 'arxiv-768', 'openai3-1536', 'openai3-3072']


def main():
    inputs = []

    def read(root, path):
        data = (root / path).read_bytes()
        inputs.append(dict(repository=root.name, path=path,
                           sha256=hashlib.sha256(data).hexdigest()))
        return data.decode()

    parser = 'experiments/comp8800_poster_e1/analyze.py'
    read(SRC, parser)
    spec = importlib.util.spec_from_file_location('e1_round2', SRC / parser)
    e1 = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(e1)
    raw = SRC / 'experiments/comp8800_poster_e1/RAW_RESULTS'
    for pattern in ['jhq_*.json', 'cuvs_*.jsonl', 'rabitq_*.jsonl']:
        for p in sorted(raw.glob(pattern)):
            read(SRC, str(p.relative_to(SRC)))
    points, failures, _ = e1.load(str(raw))
    assert len(points) == 1590 and not failures
    cells, paths, cvs, g0_points = [], collections.Counter(), collections.defaultdict(list), []
    for p in sorted(raw.glob('jhq_*.json')):
        j = json.loads(p.read_text())
        ds = p.name.split('_')[1]
        cvs[ds].append(j['sched_cv'])
        assert j['nq'] == 1000
        for run in j['runs']:
            assert run['batch'] == run['nused'] == 1000 and run['nbatch'] == 1
            v = {x['G']: x for x in run['variants']}
            assert v[0]['recall'] == v[-1]['recall']
            assert v[-1]['final_bit_identical'] == 1000
            assert v[-1]['topck_nontie'] == 0
            group = run['sched_G']
            assert group == (4 if ds == 'vogue-768' else 0)
            paths[ds, group] += 1
            a, b = st.median(v[-1]['qps']), st.median(v[0]['qps'])
            cells.append(dict(dataset=ds, nprobe=j['nprobe'], alpha=run['alpha'],
                              groups=group, recall=v[-1]['recall'], scheduled_qps=a,
                              g0_qps=b, ratio=a/b))
            if ds == 'vogue-768':
                g0_points.append(dict(recall=v[0]['recall'], qps_A=b))
    assert len(cells) == 132
    vogue = [c for c in cells if c['dataset'] == 'vogue-768']
    assert len(vogue) == 27
    fronts = {ds: e1.pareto([p for p in points if p['dataset'] == ds
                             and p['family'] == 'JHQ-GPU v69']) for ds in DATASETS}
    rq = e1.pareto([p for p in points if p['dataset'] == 'vogue-768'
                   and p['family'] == 'IVF-RaBitQ'])
    path_matched = []
    for target in [.96, .97]:
        rb, _ = e1.at_recall_interp(rq, target)
        q4, _ = e1.at_recall_interp(fronts['vogue-768'], target)
        q0, _ = e1.at_recall_interp(e1.pareto(g0_points), target)
        path_matched.append(dict(recall=target, scheduled=q4/rb, one_block=q0/rb,
                                 scheduled_qps=q4, g0_qps=q0, rabitq_qps=rb))
    target = ROOT / 'tables/ch7/e1_paths.tex'
    lines = ['% Generated by scripts/audit_ch7_round2.py; no new GPU run.',
             r'\begin{tabular}{@{}rrr@{}}', r'\toprule',
             r'Recall & $\gscan=4$ / RaBitQ & $\gscan=0$ / RaBitQ \\', r'\midrule']
    lines += [f"{r['recall']:.2f} & {r['scheduled']:.3f} & {r['one_block']:.3f}"+r' \\'
              for r in path_matched]
    lines += [r'\bottomrule', r'\end{tabular}', '']
    target.write_text('\n'.join(lines))

    # Slopes of actual adjacent Pareto segments, without the 5e-4 snap rule.
    # At arXiv's exact 0.97 knot report both adjacent one-sided segments.
    slopes = []
    for ds, front in fronts.items():
        for a, b in zip(front, front[1:]):
            if a['recall'] <= .97 <= b['recall']:
                beta = abs(math.log(b['qps_A']/a['qps_A'])/(b['recall']-a['recall']))
                slopes.append(dict(dataset=ds, lower_recall=a['recall'], upper_recall=b['recall'],
                                   log_slope=beta, fractional_change_per_1e3=math.expm1(beta*.001),
                                   fractional_change_per_2e_minus4=math.expm1(beta*.0002)))
    cold = json.loads(read(SRC, 'experiments/comp8800_poster_e1/RAW_RESULTS/jhqcold_vogue-768.json'))
    cached = json.loads((raw/'jhq_vogue-768_np128_130643.json').read_text())
    cr = next(r for r in cached['runs'] if r['alpha'] == 64)
    getrec = lambda run: next(v['recall'] for v in run['variants'] if v['G'] == -1)
    cold_delta = getrec(cold['runs'][0])-getrec(cr)
    assert abs(cold_delta-.0002) < 1e-12

    # Winning a four-arm race is not a paired binary sign trial.
    lut = collections.defaultdict(dict)
    for p in sorted((SRC/'experiments/adc_v69/RAW_LUT').glob('v71_g*.json')):
        match = re.fullmatch(r'v71_g([1248])_(.+)_np(\d+)\.json', p.name)
        if not match:
            continue
        group, ds, probes = match.groups()
        j = json.loads(read(SRC, str(p.relative_to(SRC))))
        r = j['runs'][0]
        q = st.median(next(v['qps'] for v in r['variants'] if v['G'] == -1))
        lut[ds, int(probes)][int(group)] = q
    assert len(lut) == 24 and all(set(x) == {1, 2, 4, 8} for x in lut.values())
    pairwins = sum(v[2] > v[1] for v in lut.values())
    bestwins = sum(max(v, key=v.get) == 2 for v in lut.values())
    assert pairwins == 23 and bestwins == 22
    nominal_one = sum(math.comb(24, k) for k in range(22, 25))/2**24
    per_dataset = {ds: math.exp(st.mean(math.log(v[2]/v[1]) for (d, _), v in lut.items() if d == ds))
                   for ds in sorted({d for d, _ in lut})}

    pilot = list(csv.DictReader(read(SRC, 'experiments/residual_aware_bound/RECALL_COMPARISON.csv').splitlines()))
    pilot_summary = []
    for tag in sorted({r['tag'] for r in pilot}):
        rows = [r for r in pilot if r['tag'] == tag]
        mean = lambda key: st.mean(float(r[key]) for r in rows)
        pilot_summary.append(dict(workload=tag, queries=len(rows),
                                  recall_selected=mean('recall_v65'), recall_full_ivf=mean('recall_full_ivf'),
                                  recall_gain=mean('recall_full_ivf')-mean('recall_v65'),
                                  identical_queries=sum(float(r['overlap_v65_full']) == 1 for r in rows)))
    assert len(pilot_summary) == 7
    read(SRC, 'experiments/residual_aware_bound/analyze.py')
    read(SRC, 'examples/demo_jhq_v66_bound_pilot.cu')
    for path in ['scripts/download_jhq_datasets.py', 'scripts/preprocess.py',
                 'experiments/comp8800_poster_e1/run_e1.sh',
                 'experiments/jhq_cpu_grouped_refine/REPORT_CN.md',
                 'experiments/jhq_cpu_grouped_refine/README.md', 'results/cpu_baseline/README.md',
                 'results/jhq_cpu_ivf_vogue-768.csv']:
        read(SRC, path)
    for path in ['scripts/audit_ch7_round2.py', 'data/ch7/round2-sources.json',
                 'Makefile', 'scripts/build_zh_tables.py',
                 'tables/ch7/e1_paths.tex', 'zh/tables/e1_paths.tex',
                 'chapters/07-evaluation.tex', 'zh/chapters/07-evaluation.tex',
                 'appendices/a-reproducibility.tex', 'references.bib',
                 'assessment/ch7-round2-response.txt', 'assessment/ch7-pending-experiments.txt']:
        if (ROOT/path).exists():
            read(ROOT, path)
    result = dict(date='2026-10-28', scope='Offline second-review audit; no CUDA or implementation change',
                  paths=[dict(dataset=d, groups=g, cells=n) for (d, g), n in sorted(paths.items())],
                  cv={d: [min(v), max(v)] for d, v in cvs.items()},
                  vogue_matched=path_matched, vogue_cells=vogue,
                  vogue_slow_cells=[c for c in vogue if c['ratio'] < 1],
                  frontier_local_slopes=slopes,
                  vogue_single_cold_cache_recall_delta=cold_delta,
                  training_scope='one paired observation is not a bound on independent retraining or vertical QPS changes',
                  lut=dict(four_arm_wins=bestwins, paired_g2_vs_g1_wins=pairwins,
                           dataset_gmean_g2_over_g1=per_dataset,
                           hypothetical_iid_22_of_24_one_sided=nominal_one,
                           hypothetical_iid_22_of_24_two_sided=2*nominal_one,
                           inferential_status='not adopted: four-arm winner count and reused dataset/index across probes'),
                  pilot=pilot_summary,
                  openai_pairing='supplement checks all query vectors and 10299 strided base rows; strong vector-row correspondence, original entity IDs not exported',
                  inputs=inputs)
    (ROOT/'data/ch7/round2-audit.json').write_text(json.dumps(result, indent=2)+'\n')
    print(json.dumps({k: result[k] for k in ['paths', 'cv', 'vogue_matched', 'vogue_slow_cells',
                                             'frontier_local_slopes', 'lut', 'pilot']}, indent=2))
    print(f'Hashed {len(inputs)} inputs; 132 E1 cells, 24 LUT cells, seven pilot arms checked.')


if __name__ == '__main__':
    main()
