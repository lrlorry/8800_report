#!/usr/bin/env python3
"""Audit existing JHQ_GPU measurements and generate Chapter 7 tables/figures.

This is an offline analysis: it never runs a GPU benchmark or changes JHQ_GPU.
Usage: python3 scripts/build_ch7.py --source ../JHQ_GPU
"""
import argparse
import collections
import csv
import hashlib
import importlib.util
import json
import math
import os
import re
import shutil
import statistics as st
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
DS = ['vogue-768', 'arxiv-768', 'openai3-1536', 'openai3-3072', 'bge-m3', 'stella']
NAME = dict(zip(DS, ['Vogue', 'arXiv', 'OpenAI-1536', 'OpenAI-3072', 'BGE', 'Stella']))
METHODS = ['JHQ-GPU v69', 'CAGRA fp32', 'CAGRA int8', 'IVF-RaBitQ', 'IVF-PQ', 'GPU brute force']
SHAPE = dict(zip(DS, [(932328,768,4096), (2253000,768,8192), (999000,1536,8192),
                         (999000,3072,8192), (10091524,1024,32768), (17776615,1024,32768)]))


def gmean(xs):
    return math.exp(st.mean(math.log(x) for x in xs))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--source', type=Path, default=ROOT.parent/'JHQ_GPU')
    args = ap.parse_args()
    src = args.source.resolve()
    out = ROOT/'data/ch7'
    fig = ROOT/'figures/ch7'
    tab = ROOT/'tables/ch7'
    for p in (out, fig, tab):
        p.mkdir(parents=True, exist_ok=True)
    ledger = {}

    def track(p):
        p = Path(p)
        ledger[str(p.relative_to(src))] = hashlib.sha256(p.read_bytes()).hexdigest()
        return p

    def read(p):
        return track(src/p).read_text()

    def load(p):
        return json.loads(read(p))

    def table(name, spec, head, rows):
        text = ['% Generated by scripts/build_ch7.py; do not edit numbers manually.',
                r'\begin{tabular}{@{}'+spec+r'@{}}', r'\toprule',
                ' & '.join(head)+r' \\', r'\midrule']
        text += [' & '.join(map(str,row))+r' \\' for row in rows]
        text += [r'\bottomrule',r'\end{tabular}','']
        (tab/f'{name}.tex').write_text('\n'.join(text))

    # Existing parser is a standard-library module. Do not invoke its CLI,
    # which writes into the implementation repository.
    parser_path = track(src/'experiments/comp8800_poster_e1/analyze.py')
    spec = importlib.util.spec_from_file_location('e1_ch7', parser_path)
    e1 = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(e1)
    e1raw = src/'experiments/comp8800_poster_e1/RAW_RESULTS'
    for pattern in ['jhq_*.json','cuvs_*.jsonl','rabitq_*.jsonl']:
        for p in sorted(e1raw.glob(pattern)):
            track(p)
    points, failures, indexes = e1.load(str(e1raw))
    assert len(points) == 1590 and not failures
    assert all(not p['flags'] for p in points)
    families = {(d,m):[p for p in points if p['dataset']==d and p['family']==m and e1.valid(p)]
                for d in DS[:4] for m in METHODS}
    fronts = {key:e1.pareto(v) for key,v in families.items()}
    targets = [0.90,0.92,0.94,0.95,0.96,0.97,0.98,0.985,0.99,0.995]
    matched = []
    for ds in DS[:4]:
        for target in targets:
            jq,jkind = e1.at_recall_interp(fronts[ds,METHODS[0]], target)
            jm = e1.at_recall_measured(families[ds,METHODS[0]],target)
            for method in METHODS[1:]:
                oq,kind = e1.at_recall_interp(fronts[ds,method],target)
                om = e1.at_recall_measured(families[ds,method],target)
                matched.append(dict(dataset=ds,recall=target,other=method,
                    jhq_interp=jq,other_interp=oq,ratio_interp=jq/oq if jq and oq else None,
                    jhq_measured=jm,other_measured=om,ratio_measured=jm/om if jm and om else None,
                    jhq_kind=jkind,other_kind=kind))
    # Check the archived matched table rather than assuming its prose is current.
    old=list(csv.DictReader(read('experiments/comp8800_poster_e1/E1_matched.csv').splitlines()))
    oldmap={(x['dataset'],float(x['recall']),x['other']):x for x in old}
    verified=0
    for row in matched:
        prev=oldmap.get((row['dataset'],row['recall'],row['other']))
        if prev and row['ratio_interp'] is not None and prev['ratio_interp']:
            assert abs(row['ratio_interp']-float(prev['ratio_interp'])) < 0.000051
            verified += 1
    matched97=[]
    for ds in DS[:4]:
        get=lambda m:next(x for x in matched if x['dataset']==ds and x['recall']==.97 and x['other']==m)
        cg,rb=get('CAGRA fp32'),get('IVF-RaBitQ')
        matched97.append([NAME[ds],f"{cg['jhq_interp']/1000:.1f}",
            f"{cg['ratio_interp']:.3f} / {cg['ratio_measured']:.3f}",
            f"{rb['ratio_interp']:.3f} / {rb['ratio_measured']:.3f}"])
    table('matched97','lrrr',['Dataset','JHQ kQPS','vs CAGRA fp32','vs IVF-RaBitQ'],matched97)
    nondet=collections.Counter(p['family'] for p in points if p['deterministic'] is False)

    # Repeat-call determinism (A) and cross-protocol equality (B versus A)
    # are different diagnostics. The old report counted their union.
    raw_baselines=[]
    for pattern in ['cuvs_*.jsonl','rabitq_*.jsonl']:
        for p in sorted(e1raw.glob(pattern)):
            raw_baselines += [x for ln in p.read_text().splitlines()
                              if (x:=json.loads(ln)).get('type')=='point']
    e1_diagnostics=dict(
        repeat_A=sum(x.get('deterministic') is False for x in raw_baselines),
        B_vs_A=sum(x.get('b_matches_a') is False for x in raw_baselines),
        union=sum(x.get('deterministic') is False or x.get('b_matches_a') is False for x in raw_baselines),
        reduced_calls=sum(x['calls_per_round']<24 for x in raw_baselines))
    assert e1_diagnostics==dict(repeat_A=369,B_vs_A=367,union=401,reduced_calls=274)
    fast_rq=[x for x in raw_baselines if x['method']=='ivf-rabitq'
             and st.median(t for rr in x['A']['call_ms'] for t in rr)<10]
    fast_calls=[t for x in fast_rq for rr in x['A']['call_ms'] for t in rr]
    e1_diagnostics['rabitq_fast_call_trace']=dict(calls=len(fast_calls),
        calls_30_to_60ms=sum(30<=t<=60 for t in fast_calls),max_ms=max(fast_calls))
    e1_memory={};ceilings={};sensitivity=[];round_spread={}
    for ds in DS[:4]:
        jp=families[ds,METHODS[0]]
        cp=[x for x in indexes if x['dataset']==ds and x['method']=='cagra']
        contexts={x['ctx_mib'] for x in cp}
        assert contexts=={507.2}
        jm=[(p['mem_used_mib']-507.2)/1024 for p in jp]
        cm=[p['index_mib']/1024 for p in cp]
        ci=[p['index_mib']/1024 for p in indexes
            if p['dataset']==ds and p['method']=='cagra-int8']
        assert ci
        e1_memory[ds]=dict(jhq_gib=[min(jm),max(jm)],cagra_index_gib=[min(cm),max(cm)],
                           cagra_int8_index_gib=[min(ci),max(ci)],
                           ratio=[min(jm)/max(cm),max(jm)/min(cm)],context_mib=507.2)
        ceilings[ds]={m:max(p['recall'] for p in families[ds,m]) for m in METHODS}
        rp=families[ds,'IVF-RaBitQ']
        round_spread[ds]=st.median((p['qps_A_max']-p['qps_A_min'])/p['qps_A'] for p in rp)
        jf=e1.pareto([dict(p,qps_A=p['qps_p50']) for p in jp])
        rf=e1.pareto([dict(p,qps_A=p['qps_p50']) for p in rp])
        for target in targets:
            a,_=e1.at_recall_interp(jf,target);b,_=e1.at_recall_interp(rf,target)
            sensitivity.append(dict(dataset=ds,recall=target,ratio=a/b if a and b else None))
    def interval(xs,dp=2):
        return f'{min(xs):.{dp}f}--{max(xs):.{dp}f}'
    table('e1_memory','lrrr',['Dataset',r'\shortstack{JHQ net\\process GiB}',
          r'\shortstack{CAGRA fp32\\index GiB}',r'\shortstack{CAGRA int8\\index GiB}'],
          [[NAME[d],interval(e1_memory[d]['jhq_gib']),interval(e1_memory[d]['cagra_index_gib']),
            interval(e1_memory[d]['cagra_int8_index_gib'])] for d in DS[:4]])

    # Six-dataset held-out budget protocol, parsed from printed measurements.
    cells={};cur=None
    budget_text=read('experiments/adc_v69/RAW/budget_v69.log')
    for line in budget_text.splitlines():
        m=re.match(r'### (\S+) M=(\d+) nlist=(\d+) np=(\d+)',line)
        if m:
            cur=(m[1],int(m[4])); cells[cur]={'fixed':{},'rule':{},'enum':{},'nlist':int(m[3])}
            continue
        if cur is None: continue
        c=cells[cur]
        m=re.match(r'split: (\d+) calibration queries, (\d+) held-out',line)
        if m:c['cal_n'],c['test_n']=map(int,m.groups())
        m=re.match(r'ARM FIXED alpha=([\d.]+)\s+recall=([\d.]+) qps=(\d+)',line)
        if m:c['fixed'][int(float(m[1]))]=dict(recall=float(m[2]),qps=int(m[3]))
        m=re.match(r'ARM ORACLE alpha=([\d.]+) tau=([\d.]+) ceiling=([\d.]+) recall=([\d.]+) qps=(\d+)',line)
        if m:c['oracle']=dict(alpha=int(float(m[1])),tau=float(m[2]),ceiling=float(m[3]),recall=float(m[4]),qps=int(m[5]))
        m=re.match(r'ARM FULL alpha=([\d.]+) recall=([\d.]+) qps=(\d+) cal_ms=([\d.]+)',line)
        if m:c['full']=dict(alpha=int(float(m[1])),recall=float(m[2]),qps=int(m[3]),cal_ms=float(m[4]))
        m=re.match(r'ARM RULE S=(\d+)\s+reps=(\d+) cal_ms=([\d.]+) mean_loss=([\d.]+) p95_loss=([\d.]+) frac_over_1e-3=([\d.]+) median_alpha=(\d+) mean_qps=(\d+)',line)
        if m:
            c['rule'][int(m[1])]=dict(reps=int(m[2]),cal_ms=float(m[3]),mean_loss=float(m[4]),
                p95_loss=float(m[5]),over=float(m[6]),alpha=int(m[7]),qps=int(m[8]))
        m=re.match(r'ARM ENUM S=(\d+)\s+reps=(\d+) disagree=(\d+)/(\d+) enum_ms=([\d.]+) bisect_ms=([\d.]+)',line)
        if m:c['enum'][int(m[1])]=dict(reps=int(m[4]),different=int(m[3]),enum_ms=float(m[5]),bisect_ms=float(m[6]))
    assert len(cells)==12 and all(len(c['fixed'])==8 and len(c['rule'])==3 for c in cells.values())
    assert all(abs(c['fixed'][200]['recall']-c['oracle']['ceiling'])<1e-9 for c in cells.values())
    budgets=[]; quality=[];economics=[]
    for (ds,np),c in cells.items():
        r=c['rule'][128]; base=c['fixed'][100]; base64=c['fixed'][64]
        saving=c['test_n']*1000*(1/base['qps']-1/r['qps'])
        payback=r['cal_ms']/saving if saving>0 else None
        # Existing figures use 500-query equivalents, including Stella (499 held out).
        payback500=r['cal_ms']/(500000*(1/base['qps']-1/r['qps'])) if saving>0 else None
        saving64=c['test_n']*1000*(1/base64['qps']-1/r['qps'])
        payback64=r['cal_ms']/saving64 if saving64>0 else None
        x=dict(dataset=ds,nprobe=np,**r,fixed_recall=base['recall'],fixed_qps=base['qps'],
            approx_selected_recall=c['oracle']['ceiling']-r['mean_loss'],oracle=c['oracle'],
            gain=r['qps']/base['qps'],test_n=c['test_n'],payback=payback,payback500=payback500,
            gain64=r['qps']/base64['qps'],fixed64_qps=base64['qps'],fixed64_recall=base64['recall'],payback64=payback64,
            full=c['full'])
        budgets.append(x)
        quality.append([NAME[ds],np,f"{r['alpha']} / {c['oracle']['alpha']}",f"{base['recall']:.4f}",
            f"{x['approx_selected_recall']:.4f}",f"{round(r['over']*r['reps'])}/{r['reps']}",f"{r['p95_loss']:.4f}"])
        economics.append([NAME[ds],np,f"{base['qps']/1000:.1f}",f"{r['qps']/1000:.1f}",f"{x['gain']:.3f}",
            f"{x['gain64']:.3f}",
            f"{r['cal_ms']:.1f}",f"{payback:.1f}" if payback else 'Never',
            'Pass' if c['oracle']['ceiling']-base['recall']<=.001+1e-9 else 'Fail'])
    table('budget_quality','lrrrrrr',['Dataset','Probe',r'$\alpha$: rule/oracle',r'$R_{100}$',r'$\overline{R}_{\rm rule}$','Losses',r'$L_{95}$'],quality)
    table('budget_cost','lrrrrrrrr',['Dataset','Probe',r'$Q_{100}$',r'$\overline Q_{\rm rule}$',r'vs 100',r'vs 64','Cal. ms','Batches',r'\shortstack{Fixed 100\\quality}'],economics)
    full_rows=[];full_audit=[]
    for (ds,np),c in cells.items():
        f=c['full'];loss=c['oracle']['ceiling']-f['recall']
        x=dict(dataset=ds,nprobe=np,alpha=f['alpha'],loss=loss,qps=f['qps'],cal_ms=f['cal_ms'],
               gain100=f['qps']/c['fixed'][100]['qps'],gain64=f['qps']/c['fixed'][64]['qps'],
               oracle_fraction=f['qps']/c['oracle']['qps'],test_n=c['test_n'],
               fixed100_qualifies=c['oracle']['ceiling']-c['fixed'][100]['recall']<=.001+1e-9)
        full_audit.append(x)
        full_rows.append([NAME[ds],np,f['alpha'],f"{loss:.4f}",f"{f['qps']/1000:.1f}",
                          f"{x['gain100']:.3f}",f"{x['oracle_fraction']:.3f}",f"{f['cal_ms']:.1f}"])
    table('budget_full','lrrrrrrr',['Dataset','Probe',r'$\alpha_{\rm full}$','Loss',r'$Q_{\rm full}$','vs 100','vs oracle','Cal. ms'],full_rows)
    full_summary=dict(rows=full_audit,qualified=sum(x['loss']<=.001+1e-9 for x in full_audit),
                      max_loss=max(x['loss'] for x in full_audit),
                      gmean_vs100=gmean(x['gain100'] for x in full_audit),
                      gmean_vs100_qualified_control=gmean(x['gain100'] for x in full_audit if x['fixed100_qualifies']),
                      cal_ms_range=[min(x['cal_ms'] for x in full_audit),max(x['cal_ms'] for x in full_audit)])
    assert full_summary['qualified']==12 and full_summary['max_loss']<.00061
    budget64=dict(gmean=gmean(x['gain64'] for x in budgets),wins=sum(x['gain64']>1 for x in budgets),
                  range=[min(x['gain64'] for x in budgets),max(x['gain64'] for x in budgets)],
                  payback_range=[min(x['payback64'] for x in budgets if x['payback64']),
                                 max(x['payback64'] for x in budgets if x['payback64'])])
    enum_ratios=[e['enum_ms']/e['bisect_ms'] for c in cells.values() for e in c['enum'].values()]
    enum_total=sum(e['reps'] for c in cells.values() for e in c['enum'].values())
    assert enum_total==2304 and not sum(e['different'] for c in cells.values() for e in c['enum'].values())
    fixed_summary=[]
    for a in [2,4,8,16,32,64,100,200]:
        losses=[c['oracle']['ceiling']-c['fixed'][a]['recall'] for c in cells.values()]
        # Printed recall has four decimals; do not infer borderline decisions.
        passed=sum(x<=.001+1e-9 for x in losses)
        qualifying=[c for c,loss in zip(cells.values(),losses) if loss<=.001+1e-9]
        max_penalty=max((1-c['fixed'][a]['qps']/c['oracle']['qps'] for c in qualifying),default=None)
        fixed_summary.append(dict(alpha=a,qualified=passed,worst_loss=max(losses),worst_qps_penalty=max_penalty))
    table('fixed_budgets','rrrr',[r'$\alpha$','Qualifying cells','Worst recall loss','Max qualifying QPS deficit'],
          [[x['alpha'],f"{x['qualified']}/12",f"{x['worst_loss']:.4f}",
            f"{100*x['worst_qps_penalty']:.1f}\\%" if x['worst_qps_penalty'] is not None else '--'] for x in fixed_summary])
    historical=read('paper_adc2026/data/budget_arms.log')
    old_base=None;old_gains=[];old_cost=[]
    for line in historical.splitlines():
        m=re.match(r'ARM FIXED alpha=100\s+recall=[\d.]+ qps=(\d+)',line)
        if m:old_base=int(m[1])
        m=re.match(r'ARM RULE S=128\s+reps=64 cal_ms=([\d.]+).*mean_qps=(\d+)',line)
        if m:old_gains.append(int(m[2])/old_base);old_cost.append(float(m[1]))
    assert len(old_gains)==12
    historical_budget=dict(version='v57',wins=sum(v>1 for v in old_gains),
        winning_gain_range=[min(v for v in old_gains if v>1),max(old_gains)],
        cal_ms_range=[min(old_cost),max(old_cost)])

    # Current LUT granularity: 96 configurations, all four groups in 24 cells.
    lut={}
    for p in sorted((src/'experiments/adc_v69/RAW_LUT').glob('v71_g*_np*.json')):
        m=re.fullmatch(r'v71_g([1248])_(.+)_np(\d+)\.json',p.name)
        if not m:continue
        j=json.loads(track(p).read_text());v=next(v for r in j['runs'] for v in r['variants'] if v['G']==-1)
        lut.setdefault((m[2],int(m[3])),{})[int(m[1])]=dict(qps=st.median(v['qps']),recall=v['recall'],rounds=v['qps'])
    assert len(lut)==24 and all(len(c)==4 for c in lut.values())
    wins=collections.Counter(max(c,key=lambda g:c[g]['qps']) for c in lut.values())
    lut_spread=max(max(v['recall'] for v in c.values())-min(v['recall'] for v in c.values()) for c in lut.values())
    lut_ratios=[c[2]['qps']/c[1]['qps'] for c in lut.values()]
    assert wins[2]==22 and lut_spread<.000101

    # Historical factorial packing comparison: one result per arm, not new repeats.
    layout={}
    for line in read('paper_adc2026/data/layout6.log').splitlines():
        m=re.match(r'\s*(\S+)\s+M=(\d+)\s+layout=(\w+)\s+G=(\d+)\s+np=(\d+)\s+recall=([\d.]+)\s+qps=(\d+)',line)
        if m:layout[m[1],m[3],int(m[4]),int(m[5])]=(float(m[6]),int(m[7]))
    packing=[]
    for ds in DS:
        for np in [8,32,128,512]:
            for g in [1,2]:
                b,w=layout[ds,'byte',g,np],layout[ds,'word',g,np]
                packing.append(dict(dataset=ds,nprobe=np,g=g,gain=w[1]/b[1],recall_difference=w[0]-b[0]))
    assert len(packing)==48

    # Recompute scheduling speedups from the five per-round raw arrays.
    pipeline=[]; pipe_checks=[]
    train_configs={('arxiv-768',128,100),('arxiv-768',128,200),('vogue-768',128,64),('openai3-3072',128,4)}
    for p in sorted((src/'experiments/pipeline_campaign/exp47/raw/bench').glob('*.json')):
        j=json.loads(track(p).read_text());ds=p.name.split('_np')[0]
        for run in j['runs']:
            v={v['G']:v for v in run['variants']}
            assert all(len(x['qps'])==5 for x in v.values())
            speed={g:st.median(a/b for a,b in zip(x['qps'],v[0]['qps'])) for g,x in v.items()}
            fixed=max(speed[g] for g in [0,102,104,108])
            pipeline.append(dict(dataset=ds,nprobe=j['nprobe'],alpha=run['alpha'],batch=run['batch'],
                nused=run['nused'],cv=j['sched_cv'],sched_G=run['sched_G'],speed=speed,
                training=(ds,j['nprobe'],run['alpha']) in train_configs,regret=fixed/speed[-1]))
            for g,x in v.items():
                if g!=0:
                    pipe_checks.append(dict(n=run['nused'],nontie=x['topck_nontie'],same=x['final_same_set'],order=x['final_same_order']))
    assert sum(x['n'] for x in pipe_checks)==234320
    assert not sum(x['nontie']+x['n']-x['same'] for x in pipe_checks)
    pipe_summary=[]
    for b in [8,32,256,1000]:
        rows=[r for r in pipeline if r['batch']==b];held=[r for r in rows if not r['training']]
        pipe_summary.append(dict(batch=b,n=len(rows),nheld=len(held),
            gains={g:gmean([r['speed'][g] for r in rows]) for g in [102,104,108,-1]},
            held_gain=gmean(r['speed'][-1] for r in held),worst_regret=max(r['regret'] for r in rows)))
    table('scheduling','rrrrrrr',['Batch','Cells',r'$g_s=2$',r'$g_s=4$',r'$g_s=8$','Scheduled','Held out'],
          [[r['batch'],r['n']]+[f"{r['gains'][g]:.3f}" for g in [102,104,108,-1]]+[f"{r['held_gain']:.3f}"] for r in pipe_summary])

    # Three separate correctness levels, from raw JSON outputs.
    v62checks=[];boundchecks=[];boundperf=[]
    for p in sorted((src/'experiments/pipeline_v62/raw/check').glob('*.json')):
        j=json.loads(track(p).read_text())
        for run in j['runs']:
            for v in run['variants']:
                if v['G']>0:v62checks.append(dict(n=run['nused'],**v))
    for p in sorted((src/'experiments/pipeline_campaign/exp2/v63_raw/check').glob('*.json')):
        j=json.loads(track(p).read_text())
        for run in j['runs']:
            for v in run['variants']:
                if v['G']>=100:boundchecks.append(dict(n=run['nused'],**v))
    for p in sorted((src/'experiments/pipeline_campaign/exp2/v63_raw/perf').glob('*.json')):
        if p.name=='stages_summary.json':continue
        j=json.loads(track(p).read_text())
        for run in j['runs']:
            v={v['G']:v for v in run['variants']}
            for g in [2,4,8]:
                boundperf.append(dict(batch=run['batch'],g=g,gain=st.median(a/b for a,b in zip(v[g+100]['qps'],v[g]['qps']))))
    assert len(v62checks)==64 and all(v['topck_nontie']==0 and v['final_bit_identical']==v['n'] for v in v62checks)
    assert len(boundchecks)==48 and all(v['vs_independent_topck_identical']==v['n'] and v['vs_independent_final_identical']==v['n'] for v in boundchecks)
    probe=load('experiments/practical_opt/v69_results/v69_summary.json')
    assert probe['exactness']=={'cases':1792,'failing':0}
    for ds in ['arxiv-768','vogue-768','openai3-3072']:
        read(f'experiments/practical_opt/v69_results/id_{ds}_compare.txt')
    probe_rows=[]
    for ds in ['arxiv-768','vogue-768','openai3-3072']:
        d={x['batch']:x for x in probe['timing'] if x['workload']==ds}
