#!/usr/bin/env python3
"""Reuse English Chapter 7 table data with Chinese column headings."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADERS = {
    'e1_paths': r'召回率 & $\gscan=4$ / RaBitQ & $\gscan=0$ / RaBitQ',
    'matched97': r'数据集 & JHQ kQPS & 相对 CAGRA fp32 & 相对 IVF-RaBitQ',
    'refinement': r'数据集 & $\alpha$ & L1/L0 吞吐比 & L16/L0 吞吐比 & 内核加速比',
    'probe': r'数据集 & 批大小 8 & 32 & 256 & 1,000',
    'budget_quality': r'数据集 & 探针数 & $\alpha$：规则/oracle & $R_{100}$ & $\overline{R}_{\rm rule}$ & 超标 & $L_{95}$',
    'fixed_budgets': r'$\alpha$ & 达标单元 & 最大召回率损失 & 达标单元最大 QPS 差额',
    'budget_cost': r'数据集 & 探针数 & $Q_{100}$ & $\overline Q_{\rm rule}$ & 相对 100 & 相对 64 & 校准 ms & 回本批数 & \shortstack{固定 100\\质量}',
    'budget_full': r'数据集 & 探针数 & $\alpha_{\rm full}$ & 损失 & $Q_{\rm full}$ & 相对 100 & 相对 oracle & 校准 ms',
    'scheduling': r'批大小 & 单元数 & $g_s=2$ & $g_s=4$ & $g_s=8$ & 调度 & 留出配置',
    'build_memory': r'数据集 & 训练 s & 添加 s & 合计 s & 已用 GiB & 原始 GiB & 残差占比',
    'e1_memory': r'数据集 & \shortstack{JHQ 净进程\\GiB} & \shortstack{CAGRA fp32\\索引 GiB} & \shortstack{CAGRA int8\\索引 GiB}',
}


def main():
    out = ROOT / 'zh/tables'
    out.mkdir(parents=True, exist_ok=True)
    for name, header in HEADERS.items():
        source = (ROOT / f'tables/ch7/{name}.tex').read_text()
        before, tail = source.split('\\toprule\n', 1)
        _, data = tail.split('\\midrule\n', 1)
        translated = (before + '\\toprule\n' + header + r' \\' + '\n'
                      + '\\midrule\n' + data.replace('Never', '不回本').replace('Pass', '达标').replace('Fail', '未达标'))
        translated = translated.replace(
            '% Generated by scripts/build_ch7.py; do not edit numbers manually.',
            '% Generated by scripts/build_zh_tables.py; numeric rows reuse English tables.')
        (out / f'{name}.tex').write_text(translated)
    print(f'Generated {len(HEADERS)} Chinese tables; numeric rows reused unchanged.')


if __name__ == '__main__':
    main()
